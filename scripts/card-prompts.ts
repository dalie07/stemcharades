/**
 * Write the ready-to-paste card requests for Claude, one per subject or course, from the curriculum map and the
 * cards already in the library:
 *
 *   npm run cards:prompts
 *
 * Writes content/prompts/curriculum.md (everything the game covers, with card counts) and
 * content/prompts/courses/<course>.md. Run it again after importing, so each request knows what now exists.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { COURSES, LEVELS, LEVEL_LABELS, LEVEL_UNIT, topicKey, type Card, type Level } from "../shared/src/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "content/prompts");
const TARGET = 25;
const AUDIENCE: Record<Level, string> = {
  1: "Primary: ages 5 to 11. Everyday words, short sentences, concrete examples.",
  2: "Secondary: ages 11 to 18. The core of a general secondary-school curriculum.",
  3: "University: first and second year undergraduate.",
  4: "Advanced: final-year undergraduate, postgraduate and specialist.",
};

const cards: Card[] = readdirSync(path.join(root, "content/decks"))
  .filter((f) => f.endsWith(".json"))
  .flatMap((f) => JSON.parse(readFileSync(path.join(root, "content/decks", f), "utf8")) as Card[]);
const inTopic = (course: string, topic: string) => cards.filter((c) => topicKey(c.course, c.topic) === topicKey(course, topic));

// ---- curriculum.md: everything the game covers -------------------------------------------------
let overview = `# What STEMCHARADES covers

Generated by \`npm run cards:prompts\` from \`shared/src/taxonomy.ts\` and \`content/decks\`. Do not edit by hand.

${cards.length} cards in ${COURSES.length} subjects and courses, ${COURSES.reduce((n, c) => n + c.topics.length, 0)} topics. The goal is ${TARGET} cards per topic.

`;
for (const level of LEVELS) {
  const courses = COURSES.filter((c) => c.level === level);
  overview += `## ${LEVEL_LABELS[level]} (${LEVEL_UNIT[level] === "subject" ? "subjects" : "courses"})\n\n${AUDIENCE[level]}\n\n| ${LEVEL_UNIT[level] === "subject" ? "Subject" : "Course"} | Course id | Topics (cards now) |\n|---|---|---|\n`;
  for (const c of courses) {
    overview += `| ${c.name} | \`${c.id}\` | ${c.topics.map((t) => `${t} (${inTopic(c.id, t).length})`).join(", ")} |\n`;
  }
  overview += "\n";
}
mkdirSync(path.join(outDir, "courses"), { recursive: true });
writeFileSync(path.join(outDir, "curriculum.md"), overview);

// ---- courses/<course>.md: one request per subject or course ----------------------------------
rmSync(path.join(outDir, "courses"), { recursive: true, force: true });
mkdirSync(path.join(outDir, "courses"));
for (const course of COURSES) {
  const needs = course.topics
    .map((t) => ({ topic: t, have: inTopic(course.id, t).length }))
    .map((t) => ({ ...t, need: Math.max(0, TARGET - t.have) }))
    .sort((a, b) => b.need - a.need);
  const total = needs.reduce((n, t) => n + t.need, 0);
  const existing = cards.filter((c) => c.course === course.id);
  // Answers only need to be unique within a level, so list those already used at this level, in these subjects.
  const subjectAnswers = [...new Set(cards.filter((c) => c.level === course.level && course.subjects.includes(c.subject)).map((c) => c.answers[0]!))].sort((a, b) =>
    a.localeCompare(b),
  );
  const file = `${course.id}.md`;

  const text = `# Cards for ${LEVEL_LABELS[course.level]} ${course.name}

Paste everything below the line into the same Claude chat as the card-writing rules (Prompt B in
content/prompts/README.md). Generated by \`npm run cards:prompts\`: run it again after importing.

---

Write cards for this ${LEVEL_UNIT[course.level]}.

- Course id: ${course.id}
- Level: ${AUDIENCE[course.level]}
- Name: ${course.name}
- Subject${course.subjects.length > 1 ? `s (give each card a "subject": one of ${course.subjects.map((s) => `"${s}"`).join(", ")})` : `: ${course.subjects[0]}`}

Topics, and how many new cards each needs (${total} in all):
${needs.map((t) => `- ${t.topic}: ${t.need === 0 ? "none needed (it has enough)" : `${t.need} new cards`} (has ${t.have})`).join("\n")}

${existing.length ? `Already in the library for this ${LEVEL_UNIT[course.level]}. Do not repeat these:\n${existing.map((c) => `- ${c.prompt} (${c.topic})`).join("\n")}` : `Nothing is in the library for this ${LEVEL_UNIT[course.level]} yet.`}

${subjectAnswers.length ? `Answers already used by other ${LEVEL_LABELS[course.level]} ${course.subjects.join(" and ")} cards. Do not use any of these as an answer:\n${subjectAnswers.join(", ")}` : ""}

Work through the topics in the order listed, two topics per reply, each reply one complete JSON object with
"course": "${course.id}". After each reply I will say "next". When every topic is done, say "All topics done."
`;
  writeFileSync(path.join(outDir, "courses", file), text);
}
console.log(`Wrote content/prompts/curriculum.md and ${COURSES.length} course requests in content/prompts/courses/`);
